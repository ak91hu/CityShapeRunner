interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  tShape: (id: string, defaultName: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "hu",
  setLang: () => {},
  t: (k: string) => k,
  tShape: (id: string, n: string) => n,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("hu");

  useEffect(() => {
    const saved = typeof localStorage !== "undefined" ? (localStorage.getItem("lang") as Lang) : null;
    if (saved === "hu" || saved === "en") {
      setLangState(saved);
    }
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof localStorage !== "undefined") localStorage.setItem("lang", l);
  };

  const tFn = (key: string) => DICTS[lang][key] ?? key;
  const tShapeFn = (id: string, defaultName: string) => {
    if (lang === "hu") {
      if (id && shapeNamesHu[id]) return shapeNamesHu[id];
      const guessedId = defaultName.toLowerCase().replace(/ /g, "_");
      if (shapeNamesHu[guessedId]) return shapeNamesHu[guessedId];
    }
    return defaultName;
  };
  return <I18nContext.Provider value={{ lang, setLang, t: tFn, tShape: tShapeFn }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function t(key: string): string {
  return DICTS.hu[key] ?? key;
}
